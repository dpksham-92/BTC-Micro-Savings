// ---- CONFIG ----
const BTC_PRICE_INR = 6261782.87;

// ---- DOM ----
const rangeInput = document.getElementById("amountRange");
const baseAmountText = document.getElementById("baseAmount");
const totalAmountText = document.getElementById("totalAmount");
const btcValueText = document.getElementById("btcValue");
const taglineText = document.getElementById("tagline");
const durationButtons = document.querySelectorAll(".duration-btn");

let selectedMultiplier = 6;
let selectedLabel = "6 Months";

// ---- Events ----
rangeInput.addEventListener("input", function () {
    updateValues();
});

durationButtons.forEach(button => {
    button.addEventListener("click", function () {

        durationButtons.forEach(btn => btn.classList.remove("active"));
        this.classList.add("active");

        selectedMultiplier = parseInt(this.dataset.multiplier);
        selectedLabel = this.dataset.label;

        updateValues();
    });
});

// ---- Slider Background Update ----
function updateSliderBackground() {
    const value = (rangeInput.value - rangeInput.min) /
                  (rangeInput.max - rangeInput.min) * 100;

    rangeInput.style.background =
        `linear-gradient(to right,
        #FFEA92 0%,
        #FFEA92 ${value}%,
        #e0e0e0 ${value}%,
        #e0e0e0 100%)`;
}

// ---- Calculation ----
function updateValues() {

    const baseAmount = parseInt(rangeInput.value);
    const total = baseAmount * selectedMultiplier;
    const btcAmount = total / BTC_PRICE_INR;

    baseAmountText.textContent = baseAmount.toLocaleString();
    totalAmountText.textContent = total.toLocaleString();
    btcValueText.textContent = btcAmount.toFixed(6);

    taglineText.textContent = `${selectedLabel}`;

    updateSliderBackground(); // Important: yaha call karo
}

// Initial load
updateValues();

