<script>
    function updateUI(price, change) {
      const priceEl = document.getElementById("price");
      const changeEl = document.getElementById("change");

      // Remove loading effect
      priceEl.classList.remove("loading");
      changeEl.classList.remove("loading");

      // Format INR
      const formattedPrice = price.toLocaleString("en-IN");
      priceEl.innerText = "₹ " + formattedPrice;

      if (change >= 0) {
        changeEl.innerText = "▲ " + change.toFixed(2) + "%";
        changeEl.className = "change green";
      } else {
        changeEl.innerText = "▼ " + change.toFixed(2) + "%";
        changeEl.className = "change red";
      }
    }

    // ⚡ Show cached instantly
    window.onload = () => {
      const cachedPrice = localStorage.getItem("btc_price");
      const cachedChange = localStorage.getItem("btc_change");

      if (cachedPrice && cachedChange) {
        updateUI(Number(cachedPrice), Number(cachedChange));
      }
    };

    // 🔄 Fetch fresh data
    async function getBTCPrice() {
      try {
        const res = await fetch(
          "https://api.coingecko.com/api/v3/simple/price?ids=bitcoin&vs_currencies=inr&include_24hr_change=true"
        );
        const data = await res.json();

        const price = data.bitcoin.inr;
        const change = data.bitcoin.inr_24h_change;

        // Save cache
        localStorage.setItem("btc_price", price);
        localStorage.setItem("btc_change", change);

        updateUI(price, change);

      } catch (error) {
        console.error("API Error:", error);
      }
    }

    // First API call (background)
    getBTCPrice();

    // Auto refresh every 10 sec
    setInterval(getBTCPrice, 10000);
  </script>
